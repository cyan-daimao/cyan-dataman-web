-- ------------------------------------------------------------
-- 1. 用户维度表 dim_user
-- 用途：城市用户分布、渠道来源分析
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dim_user (
    user_id         STRING  COMMENT '用户ID',
    user_name       STRING  COMMENT '用户昵称',
    city            STRING  COMMENT '城市',
    province        STRING  COMMENT '省份',
    channel         STRING  COMMENT '注册渠道：自然搜索/应用商店/微信小程序/抖音广告/百度推广/短信推送',
    register_date   STRING  COMMENT '注册日期：yyyy-MM-dd',
    gender          STRING  COMMENT '性别：男/女/未知',
    age_group       STRING  COMMENT '年龄段：18-25/26-35/36-45/46-60/60+',
    member_level    STRING  COMMENT '会员等级：普通/银卡/金卡/钻石'
)
COMMENT '用户维度表'
USING iceberg;

-- ------------------------------------------------------------
-- 2. 用户日活汇总表 dws_user_active_daily
-- 用途：各渠道DAU对比、日活趋势
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dws_user_active_daily (
    stat_date       STRING  COMMENT '统计日期：yyyy-MM-dd',
    channel         STRING  COMMENT '渠道',
    dau_cnt         BIGINT  COMMENT '日活跃用户数',
    new_user_cnt    BIGINT  COMMENT '新增用户数',
    avg_session_cnt DOUBLE  COMMENT '人均会话次数'
)
COMMENT '用户日活汇总表'
USING iceberg;

-- ------------------------------------------------------------
-- 3. 销售日报表 dws_sales_daily
-- 销售额TOP10、销售趋势、品类分析
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dws_sales_daily (
    stat_date       STRING  COMMENT '统计日期：yyyy-MM-dd',
    product_id      STRING  COMMENT '商品ID',
    product_name    STRING  COMMENT '商品名称',
    category        STRING  COMMENT '品类：数码/家电/服饰/食品/美妆/家居/运动/母婴',
    region          STRING  COMMENT '大区：华东/华南/华北/华中/西南/西北/东北',
    province        STRING  COMMENT '省份',
    sales_amt       DECIMAL(18,2) COMMENT '销售金额',
    order_cnt       BIGINT  COMMENT '订单数',
    refund_amt      DECIMAL(18,2) COMMENT '退款金额'
)
COMMENT '销售日报表'
USING iceberg;

-- ------------------------------------------------------------
-- 4. 费用月报表 dws_cost_monthly
-- 用途：Q1各部门费用占比、费用趋势
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dws_cost_monthly (
    stat_month      STRING  COMMENT '统计月份：yyyy-MM',
    department      STRING  COMMENT '部门：研发部/市场部/销售部/运营部/人力资源部/财务部/行政部',
    cost_type       STRING  COMMENT '费用类型：人力成本/市场推广/办公租金/差旅费/设备采购/培训费/外包费',
    cost_amt        DECIMAL(18,2) COMMENT '费用金额',
    budget_amt      DECIMAL(18,2) COMMENT '预算金额'
)
COMMENT '费用月报表'
USING iceberg;


